import { execFileSync } from 'node:child_process';
import { copyFileSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

type IconNode = [tag: string, attrs: Record<string, string>][];

const root = join(import.meta.dirname, '..');
const pkgDir = join(root, 'node_modules', 'lucide-static');
const { version } = JSON.parse(readFileSync(join(pkgDir, 'package.json'), 'utf8')) as { version: string };
const nodes = JSON.parse(readFileSync(join(pkgDir, 'icon-nodes.json'), 'utf8')) as Record<string, IconNode>;

const escape = (value: string) => value.replaceAll('&', '&amp;').replaceAll('"', '&quot;').replaceAll('<', '&lt;');

const funcName = (name: string) => {
  if (!/^[a-z]/.test(name)) throw new Error(`lucide icon name does not start with a letter: ${name}`);
  return name
    .split('-')
    .map((part) => part[0].toUpperCase() + part.slice(1))
    .join('');
};

const shapes = (node: IconNode) =>
  node
    .map(([tag, attrs]) => {
      const attributes = Object.entries(attrs)
        .map(([key, value]) => ` ${key}="${escape(String(value))}"`)
        .join('');
      return `<${tag}${attributes}/>`;
    })
    .join('');

const aliasShapes = (name: string) => {
  const svg = readFileSync(join(pkgDir, 'icons', `${name}.svg`), 'utf8');
  const inner = /<svg[^>]*>([\s\S]*)<\/svg>/.exec(svg)?.[1];
  if (!inner) throw new Error(`lucide alias without shapes: ${name}`);
  return inner.replaceAll(/\s*\n\s*/g, '').replaceAll(' />', '/>');
};

const sources = new Map<string, string>(Object.entries(nodes).map(([name, node]) => [name, shapes(node)]));
for (const file of readdirSync(join(pkgDir, 'icons'))) {
  const name = file.replace(/\.svg$/, '');
  if (!sources.has(name)) sources.set(name, aliasShapes(name));
}

const canonical = Object.keys(nodes);
const aliases = [...sources.keys()].filter((name) => !(name in nodes));
const byFunc = new Map<string, string>();
for (const name of canonical) {
  const fn = funcName(name);
  if (byFunc.has(fn)) throw new Error(`lucide function name collision: ${fn}`);
  byFunc.set(fn, name);
}
for (const name of aliases) {
  const fn = funcName(name);
  if (!byFunc.has(fn)) byFunc.set(fn, name);
}

const funcs = [...byFunc.keys()].sort().map((fn) => {
  const name = byFunc.get(fn)!;
  const source = sources.get(name)!;
  if (source.includes('`')) throw new Error(`lucide icon has a backtick: ${name}`);
  return `func ${fn}() *ui.SVG { return load(${JSON.stringify(name)}, \`${source}\`) }`;
});

const out = join(root, 'pkg', 'lucide', 'icons_gen.go');
writeFileSync(
  out,
  `// Code generated by scripts/gen-lucide.ts from lucide-static ${version}. DO NOT EDIT.

package lucide

import "github.com/egoist/mygo/ui"

${funcs.join('\n\n')}
`,
);
execFileSync('gofmt', ['-w', out]);
copyFileSync(join(pkgDir, 'LICENSE'), join(root, 'pkg', 'lucide', 'LICENSE'));
console.log(`wrote ${funcs.length} lucide icons to pkg/lucide/icons_gen.go`);
